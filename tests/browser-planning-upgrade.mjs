import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'

export async function runPlanningUpgradeChecks({ origin, cdp, evaluate, waitFor, click, button, field, tasks, calls, errors }) {
  const screen = async name => {
    if (!process.env.FOCUS_SCREENSHOT_DIR) return
    fs.mkdirSync(process.env.FOCUS_SCREENSHOT_DIR, { recursive: true })
    fs.writeFileSync(path.join(process.env.FOCUS_SCREENSHOT_DIR, name + '.png'), Buffer.from((await cdp('Page.captureScreenshot', { format: 'png' })).data, 'base64'))
  }
  await cdp('Page.navigate', { url: origin + '/tasks?tab=free' })
  await button('+ Thêm giờ rảnh')
  await button('Thứ Hai–Thứ Sáu')
  assert.equal(await evaluate('document.querySelectorAll("input[name=thuDuocChon]:checked").length'), 5)
  await field('input[name=gioBatDau]', '20:00')
  await field('input[name=gioKetThuc]', '23:00')
  await button('Lưu thay đổi')
  await waitFor('!document.querySelector("dialog[open]") && document.querySelectorAll(".ht-study-list .ht-item").length >= 5')
  const created = calls.filter(call => call.route === '/availability-windows/batch' && call.method === 'POST').at(-1)
  assert.deepEqual(created.body.thuTrongTuan, [1, 2, 3, 4, 5])
  assert.equal(created.body.gioBatDau, '20:00:00')
  assert.equal(calls.filter(call => call.route === '/availability-windows' && call.method === 'POST').length, 0, 'Multi-day input uses one atomic request')
  await screen('availability-weekdays')
  await button('Điều chỉnh một ngày')
  await waitFor('!!document.querySelector("input[name=ngayNgoaiLe]") && !document.querySelector("button[type=submit]").disabled')
  const exceptionDay = await evaluate('document.querySelector("input[name=ngayNgoaiLe]").value')
  await button('Lưu ngày này')
  await waitFor('document.querySelector(".ht-exception-list")?.textContent.includes("Không rảnh")')
  const skipped = calls.filter(call => /\/exceptions\/\d{4}-\d{2}-\d{2}$/.test(call.route) && call.method === 'PUT').at(-1)
  assert.equal(skipped.body.boQua, true)
  assert(skipped.route.endsWith(exceptionDay))
  await click('input[name=boQua]')
  await field('.ht-availability-exception input[type=time]', '21:00')
  await evaluate(`(() => { const input = document.querySelectorAll('.ht-availability-exception input[type=time]')[1]; Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, '22:00'); input.dispatchEvent(new Event('input', { bubbles: true })); })()`)
  await button('Lưu ngày này')
  await waitFor('document.querySelector(".ht-exception-list")?.textContent.includes("21:00–22:00")')
  await screen('availability-exception')
  await button('Dùng lại lịch lặp')
  await waitFor('!document.querySelector(".ht-exception-list")')
  await button('Đóng')

  await cdp('Page.navigate', { url: origin + '/tasks?tab=planning' })
  await click('.ht-study-settings summary')
  await waitFor('!!document.querySelector(".ht-shared-settings input[name=minutes]") && !document.querySelector(".ht-shared-settings button[type=submit]").disabled')
  await field('.ht-shared-settings input[name=minutes]', '20')
  await field('.ht-shared-settings input[name=rest]', '5')
  await field('.ht-shared-settings input[name=daily]', '120')
  await button('Lưu cài đặt')
  await waitFor('!!document.querySelector(".ht-settings-saved")')
  const settingWrite = calls.filter(call => call.route === '/study-settings' && call.method === 'PUT').at(-1)
  assert.deepEqual(settingWrite.body, { phienHocPhut: 20, nghiGiuaPhienPhut: 5, gioiHanHocMoiNgayPhut: 120 })
  await cdp('Page.navigate', { url: origin + '/focus' })
  await waitFor('document.querySelector(".focus-clock-face>strong")?.textContent === "20:00" && !document.querySelector(".focus-controls button").disabled')
  await click('button[aria-label="Tùy chọn đồng hồ"]'); await button('Cài đặt đồng hồ')
  await waitFor('document.querySelector("input[name=minutes]")?.value === "20"')
  assert.equal(await evaluate('document.querySelector("input[name=daily]").value'), '120')
  await button('Đóng')
  await cdp('Page.navigate', { url: origin + '/tasks?tab=planning' })
  await click('input[name=cachLapKeHoach]:last-of-type')
  // Chọn theo nhãn để kiểm thử không phụ thuộc cách bố trí hai lựa chọn trên giao diện.
  await evaluate('Array.from(document.querySelectorAll("label")).find(label => label.textContent.trim() === "Cập nhật phần chưa học").querySelector("input").click()')
  await button('Tạo gợi ý lịch học')
  await waitFor('!!document.querySelector(".ht-study-results")')
  const preview = calls.filter(call => call.route === '/planning/preview' && call.method === 'POST').at(-1)
  assert.equal(preview.body.capNhatKeHoach, true)
  await waitFor('!!document.querySelector(".ht-replan-summary")')
  await screen('planning-replace-preview')
  const applyBefore = calls.filter(call => call.route === '/planning/apply').length
  await evaluate('Array.from(document.querySelectorAll("button")).find(button => button.textContent.trim().startsWith("Áp dụng ") && button.textContent.includes("phiên đã chọn")).click()')
  await waitFor('document.querySelector(".ht-confirm-description")?.textContent.includes("Thay thế")')
  await button('Hủy')
  assert.equal(calls.filter(call => call.route === '/planning/apply').length, applyBefore)
  await evaluate('Array.from(document.querySelectorAll("button")).find(button => button.textContent.trim().startsWith("Áp dụng ") && button.textContent.includes("phiên đã chọn")).click()')
  await button('Áp dụng lịch')
  await waitFor('!!document.querySelector(".ht-item[data-session-id]")')
  assert.equal(calls.filter(call => call.route === '/planning/apply').length, applyBefore + 1)
  assert.deepEqual(errors, [])
  assert(tasks.length > 0)
  console.log('PASS planning upgrade UI: atomic multi-day creation, skip/override/restore date, shared server settings, focus synchronization and replacement preview/cancel. ' + calls.length + ' fixture requests.')
}
