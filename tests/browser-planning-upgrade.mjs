import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'

export async function runPlanningUpgradeChecks({ origin, cdp, evaluate, waitFor, click, button, field, tasks, calls, errors }) {
  async function reloadPlanningPage() {
    await evaluate('window.planningDocumentBeforeReload = true')
    await cdp('Page.reload')
    await waitFor('window.planningDocumentBeforeReload !== true && document.readyState === "complete"')
  }
  const screen = async name => {
    if (!process.env.FOCUS_SCREENSHOT_DIR) return
    fs.mkdirSync(process.env.FOCUS_SCREENSHOT_DIR, { recursive: true })
    fs.writeFileSync(path.join(process.env.FOCUS_SCREENSHOT_DIR, name + '.png'), Buffer.from((await cdp('Page.captureScreenshot', { format: 'png' })).data, 'base64'))
  }
  await cdp('Page.navigate', { url: origin + '/planning?tab=planning&semester=103&subject=207' })
  await waitFor('!!document.querySelector("input[name=soNgay]")')
  await field('input[name=soNgay]', '9')
  await button('Tạo hoặc sửa nhiệm vụ')
  await waitFor('location.pathname === "/tasks" && new URLSearchParams(location.search).get("returnToPlanning") === "1"')
  await field('select[aria-label="Lọc theo học kỳ"]', '')
  await click('.flow-global-create:not(:disabled)')
  await waitFor('!!document.querySelector("dialog[open] input[name=tieuDe]")')
  await field('input[name=tieuDe]', 'Nhiệm vụ bổ sung từ lập lịch')
  await field('input[name=thoiLuongDuKienPhut]', '30')
  await evaluate('document.querySelector("dialog form").requestSubmit()')
  await waitFor('!document.querySelector("dialog[open]") && document.querySelector(".ht-detail-panel")?.textContent.includes("Nhiệm vụ bổ sung từ lập lịch")')
  assert.equal(await evaluate('new URLSearchParams(location.search).get("returnToPlanning")'), '1', 'Creating a task preserves the route back to planning')
  await button('← Quay lại lập lịch')
  await waitFor('document.querySelector("input[name=soNgay]")?.value === "9"')
  assert.equal(await evaluate('new URLSearchParams(location.search).get("semester")'), '103')
  assert.equal(await evaluate('new URLSearchParams(location.search).get("subject")'), '207')
  await cdp('Page.navigate', { url: origin + '/planning' })
  await waitFor('document.querySelectorAll(".ht-planning-destination").length === 5')
  assert.equal(calls.filter(call => call.route === '/planning/apply').length, 0, 'Overview never applies a schedule')
  assert(await evaluate('!document.querySelector(".ht-task-shortcuts") && !document.querySelector(".ht-tabs").textContent.includes("Bảng trạng thái")'), 'Planning menu does not contain task navigation')
  await screen('planning-overview-desktop')
  await click('[data-planning-link=free]')
  await waitFor('document.querySelectorAll(".ht-free-day").length === 7')
  await screen('planning-free-week')
  await button('+ Thêm giờ rảnh')
  await button('Thứ Hai–Thứ Sáu')
  assert.equal(await evaluate('document.querySelectorAll("input[name=thuDuocChon]:checked").length'), 5)
  await field('input[name=gioBatDau]', '20:00')
  await field('input[name=gioKetThuc]', '23:00')
  await button('Lưu thay đổi')
  await waitFor('!document.querySelector("dialog[open]") && document.querySelectorAll(".ht-study-list .ht-item").length >= 5')
  const created = calls.filter(call => call.route === '/availability-windows/batch' && call.method === 'POST').at(-1)
  assert.deepEqual(created.body.thuTrongTuan, [1, 2, 3, 4, 5])
  assert.equal(created.body.gioBatDau, '20:00:00')
  assert.equal(calls.filter(call => call.route === '/availability-windows' && call.method === 'POST').length, 0, 'Multi-day input uses one atomic request')
  await screen('availability-weekdays')
  await waitFor('document.querySelector(".ht-free-day:first-child").textContent.includes("20:00–23:00")')
  await click('.ht-free-day:first-child > summary')
  assert(await evaluate('document.querySelector(".ht-free-day:first-child").open'))
  await screen('planning-free-week-with-data')
  await button('Danh sách')
  await button('Điều chỉnh một ngày')
  await waitFor('!!document.querySelector("input[name=ngayNgoaiLe]") && !document.querySelector("button[type=submit]").disabled')
  const exceptionDay = await evaluate('document.querySelector("input[name=ngayNgoaiLe]").value')
  await button('Lưu ngày này')
  await waitFor('document.querySelector(".ht-exception-list")?.textContent.includes("Không rảnh")')
  const skipped = calls.filter(call => /\/exceptions\/\d{4}-\d{2}-\d{2}$/.test(call.route) && call.method === 'PUT').at(-1)
  assert.equal(skipped.body.boQua, true)
  assert(skipped.route.endsWith(exceptionDay))
  await click('input[name=boQua]')
  await field('.ht-availability-exception input[type=time]', '21:00')
  await evaluate(`(() => { const input = document.querySelectorAll('.ht-availability-exception input[type=time]')[1]; Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, '22:00'); input.dispatchEvent(new Event('input', { bubbles: true })); })()`)
  await button('Lưu ngày này')
  await waitFor('document.querySelector(".ht-exception-list")?.textContent.includes("21:00–22:00")')
  await screen('availability-exception')
  await button('Dùng lại lịch lặp')
  await waitFor('!document.querySelector(".ht-exception-list")')
  await button('Đóng')

  await cdp('Page.navigate', { url: origin + '/tasks?tab=planning' })
  await waitFor('!!document.querySelector(".ht-planning-heading")')
  await screen('planning-step-one')
  await click('[data-planning-settings]')
  await waitFor('!!document.querySelector(".ht-shared-settings input[name=minutes]") && !document.querySelector(".ht-shared-settings button[type=submit]").disabled')
  await field('.ht-shared-settings input[name=minutes]', '20')
  await field('.ht-shared-settings input[name=rest]', '5')
  await field('.ht-shared-settings input[name=daily]', '120')
  await button('Lưu cài đặt')
  await waitFor('!!document.querySelector(".ht-settings-saved")')
  await button('Quay lại lập lịch')
  const settingWrite = calls.filter(call => call.route === '/study-settings' && call.method === 'PUT').at(-1)
  assert.deepEqual(settingWrite.body, { phienHocPhut: 20, nghiGiuaPhienPhut: 5, gioiHanHocMoiNgayPhut: 120 })
  await cdp('Page.navigate', { url: origin + '/focus' })
  await waitFor('document.querySelector(".focus-clock-face>strong")?.textContent === "20:00" && !document.querySelector(".focus-controls button").disabled')
  await click('button[aria-label="Tùy chọn đồng hồ"]'); await button('Cài đặt đồng hồ')
  await waitFor('document.querySelector("input[name=minutes]")?.value === "20"')
  assert.equal(await evaluate('document.querySelector("input[name=daily]").value'), '120')
  await button('Đóng')
  await cdp('Page.navigate', { url: origin + '/tasks?tab=planning' })
  await field('input[name=ngayBatDau]', new Date(Date.now() + 86400000).toISOString().slice(0, 10))
  await click('input[name=cachLapKeHoach]:last-of-type')
  // Chọn theo nhãn để kiểm thử không phụ thuộc cách bố trí hai lựa chọn trên giao diện.
  await evaluate('Array.from(document.querySelectorAll("label")).find(label => label.textContent.trim() === "Cập nhật phần chưa học").querySelector("input").click()')
  await button('Tạo gợi ý lịch học')
  await waitFor('!!document.querySelector(".ht-study-results")')
  const preview = calls.filter(call => call.route === '/planning/preview' && call.method === 'POST').at(-1)
  assert.equal(preview.body.capNhatKeHoach, true)
  await waitFor('!!document.querySelector(".ht-replan-summary")')
  assert.equal(await evaluate('document.querySelectorAll(".ht-planning-metrics > div").length'), 5)
  assert(await evaluate('document.querySelector(".ht-planning-calculation").textContent.includes("Các phiên sẽ thay thế không tính")'))
  await click('.ht-plan-review summary')
  assert.equal(await evaluate('document.querySelectorAll(".ht-plan-review li").length'), 1, 'Replacement review lists the exact old session')
  await screen('planning-replace-preview')
  const applyBefore = calls.filter(call => call.route === '/planning/apply').length
  await evaluate('Array.from(document.querySelectorAll("button")).find(button => button.textContent.trim().startsWith("Áp dụng ") && button.textContent.includes("phiên đã chọn")).click()')
  await waitFor('document.querySelector(".ht-confirm-description")?.textContent.includes("Thay thế")')
  assert.equal(await evaluate('document.querySelectorAll(".ht-confirm-description .ht-plan-review").length'), 2, 'Confirmation separates old sessions from selected new sessions')
  assert.equal(await evaluate('document.querySelectorAll(".ht-confirm-description .ht-plan-review:first-of-type li").length'), 1)
  await button('Hủy')
  assert.equal(calls.filter(call => call.route === '/planning/apply').length, applyBefore)
  await evaluate('Array.from(document.querySelectorAll("button")).find(button => button.textContent.trim().startsWith("Áp dụng ") && button.textContent.includes("phiên đã chọn")).click()')
  await button('Áp dụng lịch')
  await waitFor('!!document.querySelector("#planning-complete-title")')
  assert(await evaluate('document.querySelector(".ht-planning-steps li:last-child").getAttribute("aria-current") === "step"'))
  await screen('planning-complete')
  await button('Xem phiên tự học')
  await waitFor('!!document.querySelector(".ht-item[data-session-id]")')
  assert.equal(calls.filter(call => call.route === '/planning/apply').length, applyBefore + 1)

  async function propose(days) {
    await cdp('Page.navigate', { url: origin + '/tasks?tab=planning' })
    await field('input[name=ngayBatDau]', new Date(Date.now() + 86400000).toISOString().slice(0, 10))
    await field('input[name=soNgay]', String(days))
    await button('Tạo gợi ý lịch học')
    await waitFor('!!document.querySelector(".ht-study-results")')
  }
  const applyCount = () => calls.filter(call => call.route === '/planning/apply').length
  await propose(2)
  assert.equal(await evaluate('document.querySelector(".ht-study-planning form").hidden'), true, 'Result step hides form but keeps its inputs mounted')
  await button('← Chỉnh thông tin lập lịch')
  assert.equal(await evaluate('document.querySelector("input[name=soNgay]").value'), '2')
  await button('Xem lại lịch đề xuất')
  await click('.ht-proposal-info')
  await waitFor('document.querySelector(".ht-proposal-dialog")?.textContent.includes("Theo cấu hình học")')
  await button('Quay lại lịch đề xuất')
  assert(await evaluate('document.querySelector(".ht-metrics").textContent.includes("25 phútĐang chọn để lưu")'))
  await click('.ht-proposal:last-child input')
  await waitFor('document.querySelector(".ht-metrics").textContent.includes("20 phútĐang chọn để lưu") && document.querySelector(".ht-metrics").textContent.includes("5 phútCòn chưa xếp sau khi lưu")')
  assert(await evaluate('document.querySelector(".ht-plan-shortage").textContent.includes("bỏ chọn 5 phút")'))
  await button('Áp dụng 1 phiên đã chọn')
  assert.equal(await evaluate('document.querySelectorAll(".ht-confirm-description .ht-plan-review:last-of-type li").length'), 1, 'Confirmation shows only the selected subset')
  assert(await evaluate('document.querySelector(".ht-confirm-description").textContent.includes("20 phút")'))
  await button('Hủy')
  await click('.ht-proposal:last-child input')
  await click('.ht-proposal input')
  await waitFor('document.querySelector(".ht-metrics").textContent.includes("5 phútĐang chọn để lưu") && document.querySelector(".ht-metrics").textContent.includes("20 phútCòn chưa xếp sau khi lưu")')
  await waitFor('Array.from(document.querySelectorAll("button")).some(b => b.textContent === "Áp dụng 1 phiên đã chọn" && b.disabled)')
  await screen('planning-short-session')
  await button('Chọn cùng')
  await button('Áp dụng 2 phiên đã chọn')
  await button('Áp dụng lịch')
  await waitFor('!!document.querySelector("#planning-complete-title")')
  assert(await evaluate('document.querySelector(".ht-planning-steps li:last-child").getAttribute("aria-current") === "step"'))
  await screen('planning-complete')
  await button('Xem phiên tự học')
  await waitFor('!!document.querySelector(".ht-item[data-session-id]")')
  assert.equal(calls.filter(call => call.route === '/planning/apply').at(-1).body.phien.length, 2)

  await propose(3)
  const oldFilters = calls.filter(call => call.route === '/planning/preview').at(-1).body
  await button('Áp dụng 1 phiên đã chọn')
  await button('Áp dụng lịch')
  await waitFor('document.querySelector(".ht-planning-action")?.textContent.includes("Dữ liệu đã đổi")')
  assert.equal(await evaluate('Array.from(document.querySelectorAll("button")).some(b => b.textContent === "Thử lại cùng yêu cầu áp dụng")'), false)
  await button('Tạo lại gợi ý')
  await waitFor('!document.querySelector(".ht-planning-action")')
  assert.deepEqual(calls.filter(call => call.route === '/planning/preview').at(-1).body, oldFilters)
  await button('Áp dụng 1 phiên đã chọn')
  await button('Áp dụng lịch')
  await waitFor('!!document.querySelector("#planning-complete-title")')
  assert(await evaluate('document.querySelector(".ht-planning-steps li:last-child").getAttribute("aria-current") === "step"'))
  await screen('planning-complete')
  await button('Xem phiên tự học')
  await waitFor('!!document.querySelector(".ht-item[data-session-id]")')

  await propose(4)
  const beforeLateConfirm = applyCount()
  await button('Áp dụng 1 phiên đã chọn')
  await waitFor('!!document.querySelector(".ht-confirm-description")')
  await evaluate('window.restorePlanningClock = Date.now; const simulated = Date.now() + 120000; Date.now = () => simulated')
  await button('Áp dụng lịch')
  await waitFor('document.querySelector(".ht-planning-action")?.textContent.includes("đã qua giờ bắt đầu")')
  await screen('planning-session-started')
  assert.equal(applyCount(), beforeLateConfirm, 'A session passing its start while the confirmation dialog is open is not submitted')
  await evaluate('Date.now = window.restorePlanningClock')

  await propose(5)
  assert(await evaluate('Array.from(document.querySelectorAll(".ht-study-warnings button")).some(b => b.textContent === "Thêm giờ rảnh")'))
  await button('Mở nhiệm vụ')
  await waitFor('new URLSearchParams(location.search).has("task") && !document.querySelector(".ht-study-results")')
  await button('← Quay lại lập lịch')
  await waitFor('document.querySelector("input[name=soNgay]")?.value === "5"')
  assert.equal(await evaluate('document.querySelector("input[name=ngayBatDau]").value'), new Date(Date.now() + 86400000).toISOString().slice(0, 10))
  await reloadPlanningPage()
  await waitFor('document.querySelector("input[name=soNgay]")?.value === "5"')

  await propose(6)
  await button('Áp dụng 1 phiên đã chọn')
  await button('Áp dụng lịch')
  await waitFor('document.body.innerText.includes("Chưa rõ lịch đã được lưu chưa")')
  const lost = calls.filter(call => call.route === '/planning/apply').at(-1)
  await reloadPlanningPage()
  await waitFor('document.body.innerText.includes("Có yêu cầu áp dụng chưa xác định kết quả")')
  await button('Thử lại cùng yêu cầu áp dụng')
  await waitFor('!!document.querySelector("#planning-complete-title")')
  assert(await evaluate('document.querySelector(".ht-plan-success").textContent.includes("Thử lại không tạo thêm phiên")'))
  assert(await evaluate('document.querySelector(".ht-planning-steps li:last-child").getAttribute("aria-current") === "step"'))
  await screen('planning-complete')
  await button('Xem phiên tự học')
  await waitFor('!!document.querySelector(".ht-item[data-session-id]")')
  const retry = calls.filter(call => call.route === '/planning/apply').at(-1)
  assert.deepEqual(retry.body, lost.body)
  assert(lost.headers['Idempotency-Key'])
  assert.equal(retry.headers['Idempotency-Key'], lost.headers['Idempotency-Key'])
  assert.equal(await evaluate('document.querySelectorAll(".ht-item[data-session-id]").length'), 1)
  await cdp('Page.navigate', { url: origin + '/tasks?tab=planning' })
  await cdp('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: false })
  await waitFor('!!document.querySelector("input[name=soNgay]")')
  await waitFor('document.querySelector(".ht-tabs").hidden')
  assert(await evaluate('document.querySelector(".ht-planning-heading").getBoundingClientRect().top < innerHeight'), 'Mobile hides navigation so the form is visible immediately')
  assert(await evaluate('document.documentElement.scrollWidth <= innerWidth + 1'), 'Planning form fits mobile width')
  await screen('planning-mobile-step-one')
  await field('input[name=soNgay]', '2')
  await button('Tạo gợi ý lịch học')
  await waitFor('!!document.querySelector(".ht-study-results")')
  assert(await evaluate('document.documentElement.scrollWidth <= innerWidth + 1'), 'Proposal step fits mobile width')
  await screen('planning-mobile-step-two')
  await button('← Chỉnh thông tin lập lịch')
  await evaluate('document.querySelectorAll("input[name=phamVi]")[1].click()')
  await waitFor('!!document.querySelector(".ht-study-task-options input")')
  await click('.ht-study-task-options input')
  await field('.ht-study-picker input[type=search]', 'ghi chú')
  await waitFor('document.querySelector(".ht-study-picker").textContent.includes("Đã chọn 1 nhiệm vụ")')
  await reloadPlanningPage()
  await waitFor('document.querySelector(".ht-study-picker input[type=search]")?.value === "ghi chú" && document.querySelector(".ht-study-picker").textContent.includes("Đã chọn 1 nhiệm vụ")')
  assert.equal(await evaluate('document.querySelector("input[name=soNgay]").value'), '2', 'Reload preserves dates, duration, explicit task IDs and search together')
  assert.equal(await evaluate('document.querySelectorAll("input[name=cachLapKeHoach]")[1].checked'), true, 'Reload preserves replacement mode')
  await cdp('Page.navigate', { url: origin + '/planning' })
  await waitFor('document.querySelectorAll(".ht-planning-destination").length === 5')
  assert(await evaluate('document.documentElement.scrollWidth <= innerWidth + 1'))
  await screen('planning-overview-mobile')
  await click('[data-planning-link=free]')
  await waitFor('document.querySelectorAll(".ht-free-day").length === 7')
  assert(await evaluate('document.documentElement.scrollWidth <= innerWidth + 1'))
  await screen('planning-free-week-mobile')
  assert.deepEqual(errors, [])
  assert(tasks.length > 0)
  console.log('PASS planning upgrade UI: availability, shared settings, replacement preview/cancel, short session selection, stale preview, late confirmation, warning actions and duplicate-safe retry. ' + calls.length + ' fixture requests.')
}
