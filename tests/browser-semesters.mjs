import assert from 'node:assert/strict'
import fs from 'node:fs'

export async function runSemesterChecks({ go, input, click, waitFor, evaluate, cdp, login, fixture, calls, errors }) {
  const setField = async (id, value) => {
    await evaluate(`(() => { const field = document.getElementById(${JSON.stringify(id)}); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(field, ${JSON.stringify(value)}); field.dispatchEvent(new Event('input', { bubbles: true })); field.dispatchEvent(new Event('change', { bubbles: true })); })()`)
  }
  const saveCalls = () => calls.filter(call => call.method === 'POST' && call.route === '/api/v1/semesters').length
  await go('/login'); await login(); await waitFor('location.pathname === "/today"')
  await go('/semesters'); await waitFor('document.querySelectorAll(".semester-card").length === 2')
  await click('.heading-actions .button-primary')
  await waitFor('!!document.querySelector(".semester-editor")')
  assert.equal(await evaluate('document.querySelectorAll(".semester-required-mark").length'), 3)
  await evaluate('document.querySelector("#semester-name").focus(); document.querySelector("#semester-name").blur()')
  assert.equal(await evaluate('document.querySelectorAll(".semester-editor .form-error").length'), 0)
  const writes = saveCalls()
  await click('dialog button[type=submit]')
  await waitFor('document.querySelectorAll(".semester-editor [aria-invalid=true]").length === 3')
  assert.equal(await evaluate('document.activeElement.id'), 'semester-name')
  assert.equal(saveCalls(), writes)
  await input('name', 'Học kỳ <script>')
  await setField('semester-startDate', '01/09/2026')
  await setField('semester-startDate', '31/02/2026')
  await setField('semester-endDate', '01/09/2026')
  await click('dialog button[type=submit]')
  await waitFor('!!document.querySelector("#semester-startDate-error") && !!document.querySelector("#semester-name-error")')
  assert.equal(saveCalls(), writes, 'Invalid draft must not submit an older valid date')
  await input('name', '  học   KỲ I · 2026–2027 ')
  await setField('semester-startDate', '02/09/2026')
  await click('dialog button[type=submit]')
  await waitFor('document.querySelector("#semester-name-error")?.textContent.includes("đã tồn tại") && !!document.querySelector("#semester-endDate-error")')
  await input('name', '  Học kỳ   hè 2026 ')
  await evaluate(`(() => { const field = document.querySelector('#semester-endDate').closest('.date-input').querySelector('input[type=date]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(field, '2026-09-02'); field.dispatchEvent(new Event('input', { bubbles: true })); field.dispatchEvent(new Event('change', { bubbles: true })); })()`)
  await waitFor('document.querySelectorAll(".semester-editor [aria-invalid=true]").length === 0')
  fixture.state.saveFailure = true
  await click('dialog button[type=submit]')
  await waitFor('document.querySelector(".semester-editor")?.textContent.includes("Không thể lưu học kỳ")')
  assert.equal(await evaluate('document.querySelector("#semester-name").value'), '  Học kỳ   hè 2026 ')
  assert.equal(fixture.state.semesters.length, 2)
  fixture.state.saveFailure = false
  await click('dialog button[type=submit]'); await waitFor('!document.querySelector("dialog")')
  assert.equal(fixture.state.semesters.length, 3)
  const saved = fixture.state.semesters.at(-1)
  assert.equal(saved.ten, 'Học kỳ hè 2026')
  assert.equal(saved.ngayBatDau, '2026-09-02'); assert.equal(saved.ngayKetThuc, '2026-09-02')
  await click('.semester-card .action-menu summary')
  await click('.semester-card .action-menu button')
  await waitFor('!!document.querySelector(".semester-editor")')
  await click('dialog button[type=submit]'); await waitFor('!document.querySelector("dialog")')
  await click('.semester-card .action-menu summary'); await click('.semester-card .action-menu button')
  await waitFor('!!document.querySelector(".semester-editor")')
  await input('name', saved.ten)
  await click('dialog button[type=submit]')
  await waitFor('document.querySelector("#semester-name-error")?.textContent.includes("đã tồn tại")')
  await click('dialog .button-secondary')
  fixture.state.semesters = []; fixture.state.courses = []
  await go('/subjects')
  await waitFor('!!document.querySelector(".courses-empty button:not(:disabled)")')
  await cdp('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
  await click('.courses-empty button')
  await waitFor('!!document.querySelector(".semester-editor")')
  await click('dialog button[type=submit]')
  await waitFor('(() => { const rect = document.querySelector("dialog").getBoundingClientRect(); return innerWidth === 390 && rect.width > 0 && rect.left >= 0 && rect.right <= innerWidth && rect.top >= 0 && rect.bottom <= innerHeight; })()')
  assert(await evaluate('document.documentElement.scrollWidth <= innerWidth'))
  fs.mkdirSync('.backend-integration/screenshots', { recursive: true })
  const screenshot = await cdp('Page.captureScreenshot', { format: 'png' })
  fs.writeFileSync('.backend-integration/screenshots/semester-validation-mobile.png', Buffer.from(screenshot.data, 'base64'))
  assert.deepEqual(errors, [])
  console.log('PASS: semester required fields, submit-only errors, invalid names/dates, stale date drafts, duplicate create/edit, edit self, equal dates, normalization, API failure preservation, date picker and mobile layout.')
}
