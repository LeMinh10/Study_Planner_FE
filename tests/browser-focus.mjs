  await click('button[aria-label="Tùy chọn đồng hồ"]')
  await button('Thống kê')
  await waitFor('!!document.querySelector(".focus-stat-kpis")')
  fixture.advance(901000)
  await evaluate('window.dispatchEvent(new Event("studyplanner:refresh"))')
  await waitFor('document.querySelectorAll(".focus-stat-kpis strong")[2]?.textContent === "1"')
  assert(await evaluate('!!document.querySelector(".focus-statistics[open]")'))
  await button('Xong')
  await waitFor('!!document.querySelector(".focus-completion") && document.querySelectorAll(".focus-record").length === 1')
  assert.equal(fixture.records[0].soMiliGiayDaHoc, 900000)
  assert.equal(firstTask.tienDo, firstProgress)
  assert.equal(await evaluate('document.querySelector(".focus-stats>div:first-child strong").textContent'), '1')
  await button('Cập nhật tiến độ')
  await waitFor('!!document.querySelector(".ht-detail-title h2")')
  assert.equal(await evaluate('location.pathname'), '/focus')
  await click('dialog[aria-label="Chi tiết nhiệm vụ"] .ht-detail-close')
  await click('.focus-record-task')
  await waitFor('document.querySelector(".ht-detail-title h2")?.textContent === ' + JSON.stringify(firstTask.tieuDe))
  assert.equal(await evaluate('location.pathname'), '/focus')
  await waitFor('document.querySelector(".focus-task-summary")?.textContent.includes("15 phút")')
  assert.equal(await evaluate('document.querySelectorAll(".ht-task-checklist input[type=checkbox]").length'), 2)
  assert(await evaluate('document.querySelector(".ht-content-note").textContent.includes("JOIN")'))
  await screenshot('focus-task-preview')
  await click('dialog[aria-label="Chi tiết nhiệm vụ"] .ht-detail-close')
  await click('.focus-record-open')
  await click('.focus-record-task-name')
  await waitFor('!!document.querySelector(".ht-detail-title h2")')
  assert.equal(await evaluate('document.querySelectorAll("dialog[open]").length'), 2)
  await click('dialog[aria-label="Chi tiết nhiệm vụ"] .ht-detail-close')
  await field('textarea', 'Đã hiểu JOIN. Lần tới luyện GROUP BY.')
  await button('Lưu ghi chú')
  await waitFor('!document.querySelector("dialog[open]")')
  assert.equal(fixture.records[0].ghiChu, 'Đã hiểu JOIN. Lần tới luyện GROUP BY.')
  await click('button[aria-label="Tùy chọn đồng hồ"]')
  await button('Thống kê')
  await waitFor('document.querySelectorAll(".focus-trend-track").length === 7')
  assert(await evaluate('document.querySelector(".focus-stat-kpis").textContent.includes("15 phút")'))
  await button('Ngày')
  await waitFor('document.querySelectorAll(".focus-trend-track").length === 1')
  fixture.controls.failStatistics = true
  await button('30 ngày')
  await waitFor('document.querySelector(".focus-statistics [role=alert]")?.textContent.includes("tạm gián đoạn")')
  assert(!await evaluate('!!document.querySelector(".focus-stat-kpis")'))
  fixture.controls.failStatistics = false
  await button('Thử lại')
  await waitFor('document.querySelectorAll(".focus-trend-track").length === 30')
  await click('.focus-distribution-legend button:not(:disabled)')
  await waitFor('!!document.querySelector(".ht-detail-title h2")')
  await click('dialog[aria-label="Chi tiết nhiệm vụ"] .ht-detail-close')
  const emptyDay = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Ho_Chi_Minh' }).format(new Date(Date.now() - 40 * 86400000))
  await field('input[aria-label="Ngày kết thúc thống kê"]', emptyDay)
  await waitFor('!!document.querySelector(".focus-stat-empty")')
  await button('Xong')
  await button('Nghỉ 1 phút')
  await waitFor('document.querySelector(".focus-clock-face>span").textContent.includes("Đang nghỉ")')
  await button('Bỏ qua giờ nghỉ')
  await click('.focus-task-select')
  await button('Gần đây')
  await waitFor('document.querySelector(".focus-task-options")?.textContent.includes("Ôn cơ sở dữ liệu")')
  await cdp('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
  await cdp('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
  await button('Đếm lên')
  await click('.focus-task-select')
  await click('.focus-picker-filter')
  await button('Việc cá nhân')
  await field('input[aria-label="Tìm nhiệm vụ tập trung"]', 'vbbbb')
  await waitFor('document.querySelector(".focus-task-options .focus-picker-row:not(.focus-picker-free)")?.textContent.includes("vbbbb")')
  await click('.focus-task-options .focus-picker-row:not(.focus-picker-free)')
  await button('Bắt đầu')
  await waitFor('!!document.querySelector(".focus-note-panel")')
  const activeIdBeforePreview = fixture.active().ma
  const pausesBeforePreview = calls.filter(call => call.route.endsWith('/pause')).length
  await click('button[aria-label="Tùy chọn đồng hồ"]')
  await button('Thống kê')
  await waitFor('!!document.querySelector(".focus-stat-kpis")')
  await button('Xong')
  assert.equal(fixture.active().ma, activeIdBeforePreview)
  assert.equal(fixture.active().trangThai, 'Running')
  assert.equal(calls.filter(call => call.route.endsWith('/pause')).length, pausesBeforePreview)
  fixture.advance(30000)
  await button('Tạm dừng')
  await waitFor('document.querySelector(".focus-clock-face>span").textContent.includes("Đã tạm dừng")')
  assert.equal(fixture.active().cheDo, 'Stopwatch')
  await cdp('Page.navigate', { url: origin + '/tasks' })
  await waitFor('!!document.querySelector(".focus-dock")')
  assert(await evaluate('document.querySelector(".focus-dock").textContent.includes("vbbbb")'))
  await click('.focus-dock')
  await waitFor('document.querySelector(".focus-clock-face>span")?.textContent.includes("Đã tạm dừng")')
  await button('Tiếp tục'); fixture.advance(15000)
  await button('Kết thúc'); await button('Quay lại')
  assert(fixture.active())
  await button('Kết thúc'); await button('Lưu và kết thúc')
  await waitFor('!!document.querySelector(".focus-completion") && document.querySelectorAll(".focus-record").length === 2')
  assert(fixture.records[1].soMiliGiayDaHoc >= 45000)
  assert.equal(tasks.find(t => t.tieuDe === 'vbbbb').tienDo, 0)
  await click('button[aria-label="Thêm bản ghi tập trung"]')
  const local = value => {
    const parts = Object.fromEntries(new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Ho_Chi_Minh', year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', hourCycle: 'h23' }).formatToParts(new Date(value)).map(p => [p.type, p.value]))
    return `${parts.year}-${parts.month}-${parts.day}T${parts.hour}:${parts.minute}`
  }
  await field('input[name=start]', local(Date.now() - 86400000))
  await field('input[name=end]', local(Date.now() - 86400000 + 25 * 60000))
  await field('select[name=mode]', 'Pomodoro')
  await field('textarea[name=note]', 'Buổi đọc sách hôm qua.')
  await submit()
  await waitFor('document.querySelectorAll(".focus-record").length === 3')
  assert(fixture.records.some(r => r.nhapThuCong && r.soMiliGiayDaHoc === 1500000))
  await screenshot('focus-overview-desktop')
  await click('button[aria-label="Tùy chọn đồng hồ"]')
  await button('Thống kê')
  await button('30 ngày')
  await waitFor('document.querySelectorAll(".focus-trend-track").length === 30')
  assert.equal(await evaluate('document.querySelectorAll(".focus-stat-kpis strong")[2].textContent'), '3')
  await screenshot('focus-statistics-desktop')
  await cdp('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: false })
  assert(await evaluate('document.querySelector(".focus-statistics").scrollWidth <= document.querySelector(".focus-statistics").clientWidth + 1'))
  await screenshot('focus-statistics-mobile')
  await cdp('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false })
  await button('Xong')
  await click('.focus-task-select')
  await click('dialog .focus-picker-free')
  await button('Bắt đầu')
  await waitFor('!!document.querySelector(".focus-note-panel")')
  assert.equal(fixture.active().maNhiemVu, null)
  await button('Kết thúc'); await button('Bỏ phiên')
  await waitFor('!document.querySelector("dialog[open]") && !document.querySelector(".focus-note-panel")')
  assert.equal(fixture.records.filter(r => r.trangThai === 'Completed').length, 3)
  assert.equal(fixture.records.at(-1).trangThai, 'Discarded')
  await cdp('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: false })
  await screenshot('focus-mobile')
  const parent = tasks.find(task => task.coNhiemVuCon)
  fixture.records.push({ ...fixture.records[0], ma: 10000, maNhiemVu: parent.ma, tieuDe: parent.tieuDe, cheDo: 'Stopwatch',
    soMiliGiayDaHoc: 60000, batDau: new Date(Date.now() - 7200000).toISOString(), ketThuc: new Date(Date.now() - 7140000).toISOString(), ghiChu: null })
  await evaluate('window.dispatchEvent(new Event("studyplanner:refresh"))')
  await waitFor('Array.from(document.querySelectorAll(".focus-record-task")).some(button => button.textContent === ' + JSON.stringify(parent.tieuDe) + ')')
  await evaluate('Array.from(document.querySelectorAll(".focus-record-task")).find(button => button.textContent === ' + JSON.stringify(parent.tieuDe) + ').click()')
  await waitFor('document.querySelector(".ht-detail-section")?.textContent.includes("aa")')
  await click('dialog[aria-label="Chi tiết nhiệm vụ"] .ht-detail-close')
  const mobile = await evaluate('({ width: innerWidth, scroll: document.documentElement.scrollWidth, overflow: [...document.querySelectorAll("body *")].filter(e => e.getBoundingClientRect().right > innerWidth + 2 && e.getBoundingClientRect().width > 0).slice(0,10).map(e => ({ tag: e.tagName, class: e.className, right: e.getBoundingClientRect().right })) })')
  assert(mobile.scroll <= mobile.width + 1, 'Focus page fits mobile without horizontal scrolling: ' + JSON.stringify(mobile))
  await cdp('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false })
  assert.deepEqual(errors, [])
  assert(!calls.some(c => /\/(progress|complete)$/.test(c.route) && c.method !== 'GET'), 'Timing never writes task progress')
  // Chỉ sửa nhiệm vụ sau khi đã kiểm chứng đồng hồ không tự ghi tiến độ.
  const writeField = async (selector, value) => {
    await waitFor('!!document.querySelector(' + JSON.stringify(selector) + ')')
    await evaluate(`(() => { const field = document.querySelector(${JSON.stringify(selector)}); const prototype = field.tagName === 'TEXTAREA' ? HTMLTextAreaElement.prototype : HTMLInputElement.prototype; Object.getOwnPropertyDescriptor(prototype, 'value').set.call(field, ${JSON.stringify(value)}); field.dispatchEvent(new Event('input', { bubbles: true })); })()`)
  }
