  await waitFor('!!document.querySelector(".focus-task-options .focus-picker-row:not(.focus-picker-free)")')
  await click('.focus-task-options .focus-picker-row:not(.focus-picker-free)')
  await button('Bắt đầu')
  await waitFor('!!document.querySelector(".focus-note-panel")')
  assert(await evaluate('document.querySelectorAll(".focus-timeline-tick").length >= 2'))
  assert(!await evaluate('!!document.querySelector(".focus-history")'))
  assert.equal(fixture.active().cheDo, 'Pomodoro')
  const firstTask = tasks.find(t => t.ma === fixture.active().maNhiemVu), firstProgress = firstTask.tienDo
  await field('.focus-note-panel textarea', 'Đọc phần JOIN và ghi lại các ví dụ.')
  await button('Lưu ghi chú')
  await waitFor('document.querySelector(".focus-notice")?.textContent.includes("Đã lưu ghi chú")')
  fixture.advance(15000)
  await evaluate('window.dispatchEvent(new Event("studyplanner:refresh"))')
  await waitFor('document.querySelector("[role=timer]").textContent < "14:50"')
  await screenshot('focus-running-desktop')
  await cdp('Emulation.setDeviceMetricsOverride', { width: 1280, height: 636, deviceScaleFactor: 1, mobile: false })
  assert(await evaluate('document.querySelector(".focus-controls").getBoundingClientRect().bottom <= innerHeight'), 'Timer controls fit a laptop display')
  await screenshot('focus-running-laptop')
  await cdp('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false })
  await button('Tạm dừng')
  await waitFor('document.querySelector(".focus-clock-face>span").textContent.includes("Đã tạm dừng")')
  const savedElapsed = fixture.active().soMiliGiayDaHoc
  fixture.advance(120000)
  await cdp('Page.reload')
  await waitFor('document.querySelector(".focus-clock-face>span")?.textContent.includes("Đã tạm dừng")')
  assert.equal(fixture.active().soMiliGiayDaHoc, savedElapsed)
