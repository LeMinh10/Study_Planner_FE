import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'

export async function runAttachmentChecks({ origin, cdp, evaluate, waitFor, click, button, calls, errors, userDir, controls }) {
  await cdp('Page.navigate', { url: origin + '/tasks?view=all&task=2' })
  await waitFor('document.querySelector(".ht-attachment-input")?.disabled === false')
  assert.equal(await evaluate('!!document.querySelector(".ht-attachments")'), false)
  await click('.ht-detail-header-actions .ht-row-actions-trigger:not(:disabled)')
  await evaluate('document.querySelector(".ht-attachment-input").addEventListener("click", event => { event.preventDefault(); event.target.dataset.pickerOpened = "true" }, { once: true })')
  await button('Đính kèm tệp')
  assert.equal(await evaluate('document.querySelector(".ht-attachment-input").dataset.pickerOpened'), 'true')
  const file = path.join(userDir, 'Bao cao.pdf'); fs.writeFileSync(file, '%PDF-1.7\nNoi dung kiem thu')
  async function upload(localFile = file) {
    const { root } = await cdp('DOM.getDocument')
    const { nodeId } = await cdp('DOM.querySelector', { nodeId: root.nodeId, selector: '.ht-attachment-input' })
    await cdp('DOM.setFileInputFiles', { nodeId, files: [localFile] })
  }
  await upload()
  await waitFor('document.querySelectorAll(".ht-attachments li").length === 1 && !document.querySelector(".ht-attachment-input").disabled')
  const post = calls.find(c => c.route === '/tasks/2/attachments' && c.method === 'POST')
  assert(post)
  assert(Object.entries(post.headers).some(([k,v]) => k.toLowerCase() === 'content-type' && v.startsWith('multipart/form-data; boundary=')))
  assert(Object.entries(post.headers).some(([k,v]) => k.toLowerCase() === 'authorization' && v.startsWith('Bearer ')))
  assert(Object.entries(post.headers).some(([k,v]) => k.toLowerCase() === 'if-match' && /^"ht-\d+"$/.test(v)))
  await cdp('Page.reload')
  await waitFor('document.querySelectorAll(".ht-attachments li").length === 1 && !document.querySelector(".ht-attachment-input").disabled')
  await click('.ht-attachment-name')
  await waitFor('!document.querySelector(".ht-attachment-input").disabled')
  assert(calls.some(c => /\/attachments\/1\/download$/.test(c.route)))
  // Lỗi mạng/ghi DB giữ nguyên tệp đã có; người dùng có thể nạp lại rồi thử lại.
  controls.failUpload = true
  await upload()
  await waitFor('document.querySelector(".ht-attachments").innerText.includes("Kho tệp đang bận")')
  assert.equal(await evaluate('document.querySelectorAll(".ht-attachments li").length'), 1)
  await button('Tải dữ liệu mới')
  await waitFor('!document.querySelector(".ht-attachment-input").disabled')
  await click('summary[aria-label="Tùy chọn tệp Bao cao.pdf"]')
  await click('button[aria-label="Xóa tệp Bao cao.pdf"]')
  await button('Xóa tệp')
  await waitFor('document.querySelectorAll(".ht-attachments li").length === 0 && !document.querySelector(".ht-attachment-input").disabled')
  await click('.ht-detail-header-actions .ht-row-actions-trigger:not(:disabled)')
  await button('Hoạt động nhiệm vụ')
  await waitFor('document.querySelectorAll(".ht-history li").length === 2')
  assert(await evaluate('Array.from(document.querySelectorAll(".ht-history li")).every(row => row.textContent.includes("Bao cao.pdf") && row.querySelector(".ht-history-icon svg"))'))
  assert(await evaluate('!!document.querySelector(".ht-history li[data-kind=AttachmentAdded]") && !!document.querySelector(".ht-history li[data-kind=AttachmentRemoved]")'))
  await button('Đóng')
  const before = calls.filter(c => c.method === 'POST' && c.route.endsWith('/attachments')).length
  await evaluate(`(() => { const input=document.querySelector('.ht-attachment-input'); const dt=new DataTransfer();dt.items.add(new File([new Uint8Array(10*1024*1024+1)],'Qua lon.pdf'));input.files=dt.files; input.dispatchEvent(new Event('change',{bubbles:true})); })()`)
  await waitFor('document.querySelector(".ht-attachments").innerText.includes("không vượt quá 10 MB")')
  assert.equal(calls.filter(c => c.method === 'POST' && c.route.endsWith('/attachments')).length, before)
  const webpBase64 = await evaluate("(() => { const canvas = document.createElement('canvas'); canvas.width=1000; canvas.height=500; const g=canvas.getContext('2d'); g.fillStyle='#587fb2';g.fillRect(0,0,1000,500);g.fillStyle='#edaf77';g.fillRect(0,255,1000,245);return canvas.toDataURL('image/webp').split(',')[1]; })()")
  const image = path.join(userDir, 'Anh.webp')
  const webp = Buffer.from(webpBase64, 'base64')
  fs.writeFileSync(image, webp)
  controls.nextUpload = { name: 'Anh.webp', bytes: webp }
  await upload(image)
  await waitFor('document.querySelector(".ht-attachment-preview img")?.naturalWidth === 1000')
  const downloadCalls = () => calls.filter(c => c.route.endsWith('/attachments/2/download')).length
  const previews = downloadCalls()
  assert(previews >= 1)
  assert(calls.filter(c => c.route.endsWith('/attachments/2/download')).every(c => Object.entries(c.headers)
    .some(([key, value]) => key.toLowerCase() === 'authorization' && value.startsWith('Bearer '))))
  await click('.ht-attachment-preview')
  await waitFor('document.querySelector(".ht-attachment-lightbox:modal img")?.naturalWidth === 1000')
  assert.equal(downloadCalls(), previews, 'Mở ảnh lớn sử dụng ảnh đã tải')
  if (process.env.CORE_SCREENSHOT) {
    const shot = await cdp('Page.captureScreenshot', { format: 'png' }); fs.writeFileSync(process.env.CORE_SCREENSHOT, Buffer.from(shot.data, 'base64'))
  }
  await cdp('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
  await cdp('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
  await waitFor('!document.querySelector(".ht-attachment-lightbox:modal")')
  await click('summary[aria-label="Tùy chọn tệp Anh.webp"]')
  await button('Thu nhỏ ảnh')
  await waitFor('!!document.querySelector(".ht-attachment-image-small img")')
  await click('summary[aria-label="Tùy chọn tệp Anh.webp"]')
  await button('Mở rộng ảnh')
  await waitFor('!document.querySelector(".ht-attachment-image-small")')
  await click('summary[aria-label="Tùy chọn tệp Anh.webp"]')
  await click('.ht-attachment-actions[open] button[aria-label="Tải xuống Anh.webp"]')
  await waitFor('!document.querySelector(".ht-attachment-input").disabled')
  assert.equal(downloadCalls(), previews + 1)

  // Đổi đuôi không biến nội dung SVG thành ảnh raster để hiển thị.
  const fake = path.join(userDir, 'Sai dinh dang.png')
  const svg = Buffer.from('<svg xmlns="http://www.w3.org/2000/svg"/>')
  fs.writeFileSync(fake, svg)
  controls.nextUpload = { name: 'Sai dinh dang.png', bytes: svg }
  await upload(fake)
  await waitFor('document.querySelector(".ht-attachment-preview-note")?.textContent.includes("Không xem trước được ảnh")')
  assert.equal(await evaluate('document.querySelectorAll(".ht-attachment-preview img").length'), 1)
  await click('summary[aria-label="Tùy chọn tệp Sai dinh dang.png"]')
  await click('.ht-attachment-actions[open] button[aria-label="Tải xuống Sai dinh dang.png"]')
  await waitFor('!document.querySelector(".ht-attachment-input").disabled')
  assert(calls.filter(c => c.route.endsWith('/attachments/3/download')).length >= 2)
  await cdp('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
  assert(await evaluate('document.documentElement.scrollWidth <= window.innerWidth + 1'))
  await click('.ht-attachment-preview')
  await waitFor('!!document.querySelector(".ht-attachment-lightbox:modal img")')
  assert(await evaluate('(() => { const b = document.querySelector(".ht-attachment-lightbox img").getBoundingClientRect(); return b.width > 0 && b.height > 0 && b.left >= 0 && b.right <= window.innerWidth + 1 && b.bottom <= window.innerHeight + 1; })()'))
  await click('.ht-attachment-lightbox-close')
  await waitFor('!document.querySelector(".ht-attachment-lightbox:modal")')
  assert.deepEqual(errors, [])
  console.log('PASS giao diện tệp: tải lên multipart, F5, tải xuống có JWT, lỗi/thử lại, xóa, giới hạn dung lượng, WebP, menu ảnh, từ chối ảnh giả, mobile.')
}
